import os
import pandas as pd

def get_data_paths():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(base_dir, "data")
    return {
        "events": os.path.join(data_dir, "events.csv"),
        "students": os.path.join(data_dir, "students.csv"),
        "registrations": os.path.join(data_dir, "registrations.csv"),
        "feedback": os.path.join(data_dir, "feedback.csv"),
        "output_master": os.path.join(data_dir, "cleaned_master_analytics.csv")
    }

def load_raw_datasets():
    """
    Ingests operational datasets generated by Java/MySQL into Pandas DataFrames.
    """
    paths = get_data_paths()
    print("[INGEST] Loading relational datasets from storage...")
    
    events_df = pd.read_csv(paths["events"])
    students_df = pd.read_csv(paths["students"])
    registrations_df = pd.read_csv(paths["registrations"])
    feedback_df = pd.read_csv(paths["feedback"])
    
    print(f" -> Events Loaded       : {len(events_df)} rows")
    print(f" -> Students Loaded     : {len(students_df)} rows")
    print(f" -> Registrations Loaded: {len(registrations_df)} rows")
    print(f" -> Feedback Loaded     : {len(feedback_df)} rows")
    
    return events_df, students_df, registrations_df, feedback_df

